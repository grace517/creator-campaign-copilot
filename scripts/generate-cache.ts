/**
 * Generates the demo-mode cache from the real prompts (docs/BUILD_PLAN.md: "generated once from the real prompts"):
 *
 *   data/cached/starter_dms.json     a starter DM and caption CTA for every rostered creator (PROMPTS.md call 1)
 *   data/cached/claim_judgments.json the claim judgment (call 2) on every message the app shows that passes the
 *                                    exact checks: each starter, and each creator edit in demo_state.json
 *
 *   ANTHROPIC_API_KEY=… npm run generate-cache
 *
 * Runs in GitHub Actions (.github/workflows/generate-cache.yml), which uploads the files for review before they're
 * committed. About 12–20 calls.
 */
import Anthropic from '@anthropic-ai/sdk';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JUDGMENT_MODEL, judgeClaims } from '../api/_lib/claimJudgment';
import { STARTER_MODEL, generateStarter } from '../api/_lib/starterDm';
import { parseBrief, parseDemoState, parseRoster } from '../src/data/parse';
import { exactChecks } from '../src/lib/checks';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p: string) => readFileSync(join(root, p), 'utf8');
const brief = parseBrief(read('data/brief.json'));
const roster = parseRoster(read('data/roster.csv'));
const demo = parseDemoState(read('data/demo_state.json'));

const key = process.env.ANTHROPIC_API_KEY?.trim();
if (!key) {
  console.error('Set ANTHROPIC_API_KEY to generate the cache.');
  process.exit(1);
}
const client = new Anthropic({ apiKey: key });
const out = process.env.CACHE_OUT_DIR ?? join(root, 'data/cached');
mkdirSync(out, { recursive: true });
const now = new Date().toISOString();

// The claim judgment, as the app runs it: with the product name and offer as context.
const judge = (message: string) =>
  judgeClaims(
    { message, approved_claims: brief.approved_claims, banned_claims: brief.banned_claims, product: brief.product, offer: brief.offer },
    client,
  );

// 1. Starters, one call per creator plus its claim check; regenerated once when either check fails.
const starters = [];
const starterJudgments = new Map<string, Awaited<ReturnType<typeof judge>>>(); // dm → judgment, reused below
for (const c of roster) {
  const r = await generateStarter(
    brief,
    {
      handle: c.handle,
      code: c.code,
      niche: c.niche,
      past_dms: c.past_dm_sample ? [c.past_dm_sample] : [],
      sample_captions: c.sample_captions,
    },
    client,
    judge,
  );
  if (!r.starter) throw new Error(`No starter for ${c.handle} after ${r.attempts} attempts.`);
  const failures = r.failures.map((f) => f.name);
  console.log(`${c.handle}: ${r.attempts} attempt(s)${failures.length ? `, still failing ${failures.join(', ')}` : ''}\n  ${r.starter.dm}`);
  starters.push({ handle: c.handle, ...r.starter, failures });
  if (r.judgment) starterJudgments.set(r.starter.dm, r.judgment);
}
writeFileSync(
  join(out, 'starter_dms.json'),
  `${JSON.stringify(
    {
      _note: `Demo-mode starter DMs from the real prompt (docs/PROMPTS.md call 1), generated by scripts/generate-cache.ts.`,
      source: 'model',
      model: STARTER_MODEL,
      generated_at: now,
      written_for: { product: brief.product, offer: brief.offer, link: brief.link },
      starters,
    },
    null,
    2,
  )}\n`,
);

// 2. Claim judgments on every message the app shows that passes the exact checks (PROMPTS.md: judgment runs after).
const messages = new Map<string, string>(); // message → code
for (const s of starters) messages.set(s.dm, roster.find((c) => c.handle === s.handle)!.code);
for (const d of demo.drafts_snapshot) {
  if (d.creator_dm) messages.set(d.creator_dm, roster.find((c) => c.handle === d.handle)!.code);
}
const judgments = [];
for (const [message, code] of messages) {
  if (exactChecks({ dm: message, code }, brief).some((c) => !c.passed)) continue;
  const j = starterJudgments.get(message) ?? (await judge(message));
  console.log(`judgment ${j.verdict}: ${message.slice(0, 70)}…${j.findings.map((f) => `\n  "${f.phrase}" ${f.type}`).join('')}`);
  const { source: _source, ...rest } = j;
  judgments.push({ message, ...rest });
}
writeFileSync(
  join(out, 'claim_judgments.json'),
  `${JSON.stringify(
    {
      _note: 'Demo-mode claim judgments (docs/PROMPTS.md call 2) for each message the app shows that passes the exact checks, keyed by exact text. Generated by scripts/generate-cache.ts.',
      model: JUDGMENT_MODEL,
      generated_at: now,
      judgments,
    },
    null,
    2,
  )}\n`,
);
console.log(`\nWrote ${starters.length} starters and ${judgments.length} judgments to ${out}`);
