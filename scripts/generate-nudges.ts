/**
 * Generates data/cached/nudges.json: a drafted nudge (docs/PROMPTS.md call 3) for each at-risk or waiting creator on
 * the sample campaign's Creator status day, from the real prompt. Separate from generate-cache.ts so regenerating
 * nudges never changes the reviewed starters.
 *
 *   ANTHROPIC_API_KEY=… npm run generate-nudges
 *
 * Runs in GitHub Actions (.github/workflows/generate-nudges.yml), which uploads the file for review. About 4–8 calls.
 */
import Anthropic from '@anthropic-ai/sdk';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NUDGE_MODEL, draftNudge } from '../api/_lib/nudge';
import { parseBrief, parseDemoState, parseRoster } from '../src/data/parse';
import { STEP_FOR_PROMPT, buildStatus, setupLink, shortDate } from '../src/lib/status';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p: string) => readFileSync(join(root, p), 'utf8');
const brief = parseBrief(read('data/brief.json'));
const roster = parseRoster(read('data/roster.csv'));
const demo = parseDemoState(read('data/demo_state.json'));
const snap = demo.status_snapshot;

const key = process.env.ANTHROPIC_API_KEY?.trim();
if (!key) {
  console.error('Set ANTHROPIC_API_KEY to generate nudges.');
  process.exit(1);
}
const client = new Anthropic({ apiKey: key });
const out = process.env.CACHE_OUT_DIR ?? join(root, 'data/cached');
mkdirSync(out, { recursive: true });

const rows = buildStatus({
  picks: new Set(demo.drafts_snapshot.map((d) => d.handle)),
  roster,
  today: snap.today,
  readyDaysBefore: brief.ready_deadline_days_before_post,
  testDmSent: snap.test_dm_sent,
  swaps: snap.swaps,
});

const nudges = [];
for (const r of rows.filter((r) => (r.group === 'at_risk' || r.group === 'waiting') && r.missing)) {
  const res = await draftNudge(
    {
      handle: r.creator.handle,
      postDate: shortDate(r.creator.post_date),
      readyDeadline: shortDate(r.deadline),
      today: shortDate(snap.today),
      missingStep: STEP_FOR_PROMPT[r.missing!],
      setupLink: setupLink(r.missing!, r.creator.code),
    },
    client,
  );
  if (!res.message) throw new Error(`No nudge for ${r.creator.handle}: ${res.problem}`);
  console.log(`${r.creator.handle} (${r.missing}, ${res.attempts} attempt(s)):\n  ${res.message}`);
  nudges.push({ handle: r.creator.handle, missing: r.missing, deadline: r.deadline, message: res.message });
}

writeFileSync(
  join(out, 'nudges.json'),
  `${JSON.stringify(
    {
      _note: 'Demo-mode nudges (docs/PROMPTS.md call 3) for each at-risk or waiting creator on Nov 30, keyed by handle, missing step, and deadline. Generated by scripts/generate-nudges.ts.',
      model: NUDGE_MODEL,
      generated_at: new Date().toISOString(),
      nudges,
    },
    null,
    2,
  )}\n`,
);
console.log(`\nWrote ${nudges.length} nudges to ${out}`);
